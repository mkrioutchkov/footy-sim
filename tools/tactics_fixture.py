#!/usr/bin/env python3
"""Regenerate tools/tactics_fixture.json — the committed, deterministic tactics fixture.

Run:  python3 tools/tactics_fixture.py

The regression tools used to load web/backend/data/specs/fixture-1.json, which is
gitignored and produced by an unseeded Math.random() league bootstrap — so on any
clean checkout both tools died with FileNotFoundError and the "ritual after every
change" four docs prescribe was unrunnable. This fixture is committed instead.
Regenerating it is byte-stable, but it invalidates tools/tactics_golden.json:
rerun `python3 tools/tactics_golden.py save` if you ever change the recipe.

Recipe (reproduce by re-running this file):
  * 11 players a side in the engine's default slot order
    GK FB CB CB FB CM CM CM WM CF WM (engine/engine.cpp DEF_ROLES), so the
    default 4-3-3 anchors apply and the tools' hard-coded engine ids stay valid.
  * No role/homeX/homeY keys  -> hasLayout stays false -> default anchors.
  * No directives, no weather -> a clean baseline arm.
  * Attributes: a per-role base profile plus a deterministic mulberry32 jitter
    (+/-6) seeded once at 40985, so the roster is varied enough to discriminate
    but identical on every machine.
"""
import json
import os

SEED = 40985
_s = SEED


def rnd():
    global _s
    _s = (_s + 0x6D2B79F5) & 0xFFFFFFFF
    t = _s
    t = (t ^ (t >> 15)) * (t | 1) & 0xFFFFFFFF
    t = (t ^ (t + ((t ^ (t >> 7)) * (t | 61) & 0xFFFFFFFF))) & 0xFFFFFFFF
    return ((t ^ (t >> 14)) & 0xFFFFFFFF) / 4294967296.0


SLOTS = ['GK', 'FB', 'CB', 'CB', 'FB', 'CM', 'CM', 'CM', 'WM', 'CF', 'WM']

# speed passing creativity shooting tackling positioning stamina handling height
BASE = {
    'GK': (46, 52, 44, 30, 40, 70, 62, 78, 190),
    'FB': (76, 62, 58, 44, 68, 66, 78, 20, 178),
    'CB': (60, 58, 46, 42, 78, 76, 72, 20, 187),
    'CM': (68, 74, 72, 58, 66, 70, 80, 20, 180),
    'WM': (82, 66, 74, 66, 48, 62, 76, 20, 176),
    'CF': (78, 62, 70, 82, 42, 68, 74, 20, 183),
}
KEYS = ['speed', 'passing', 'creativity', 'shooting', 'tackling',
        'positioning', 'stamina', 'handling', 'height']

FIRST = ['Alan', 'Bruno', 'Caio', 'Dario', 'Emre', 'Felix', 'Gabri', 'Hugo', 'Ivan',
         'Jonas', 'Karim', 'Luca', 'Marek', 'Niko', 'Omar', 'Pavel', 'Quinn', 'Rui',
         'Stefan', 'Tomas', 'Uros', 'Viktor']
LAST = ['Adler', 'Bakker', 'Costa', 'Dumont', 'Engel', 'Farkas', 'Grande', 'Horvat',
        'Ilic', 'Janko', 'Keller', 'Lindqvist', 'Moreno', 'Novak', 'Olsen', 'Petrov',
        'Rossi', 'Salas', 'Tavares', 'Ursu', 'Vidal', 'Weiss']


def team(name, offset):
    players = []
    for i, role in enumerate(SLOTS):
        base = BASE[role]
        attrs = {}
        for k, b in zip(KEYS, base):
            if k == 'height':
                attrs[k] = int(round(b + (rnd() * 2 - 1) * 5))
            else:
                attrs[k] = max(1, min(99, int(round(b + (rnd() * 2 - 1) * 6))))
        n = offset + i
        players.append({
            'name': f'{FIRST[n]} {LAST[n]}',
            'attrs': attrs,
            'foot': 1 if rnd() < 0.72 else (-1 if rnd() < 0.9 else 0),
        })
    return {
        'name': name,
        'tactics': {'aggression': 50, 'passingDirectness': 50, 'overlapFrequency': 50,
                    'midfieldFreedom': 50, 'defensiveLineHeight': 50},
        'players': players,
    }


spec = {
    '_note': 'GENERATED by tools/tactics_fixture.py — do not hand-edit. Deterministic base spec for tools/tactics_bench.py and tools/tactics_golden.py.',
    'seed': 40985,
    'minutes': 35,
    'home': team('Northgate United', 0),
    'away': team('Riverside Athletic', 11),
}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'tactics_fixture.json')
if len(os.sys.argv) > 1:
    out = os.sys.argv[1]
with open(out, 'w', encoding='utf-8') as f:
    json.dump(spec, f, indent=1)
    f.write('\n')
print('wrote', out, os.path.getsize(out), 'bytes')
